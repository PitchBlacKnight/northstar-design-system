#!/usr/bin/env node
/* NorthStar component drift: compares the shape of each control in Figma with what the CSS renders.
   Token drift only compares variables; this compares the components that use them: corner radius,
   height, fill and border, plus whether Figma binds the fill and radius to a variable. No npm dependencies.

     node tools/component-drift.mjs                 report; exit 1 on any difference
     node tools/component-drift.mjs --figma-script  print the read-only script to run in the Figma MCP (use_figma)
     node tools/component-drift.mjs --css           print what the CSS renders, as JSON

   The Figma side is a snapshot, tokens/figma-components.json, because reading the file needs the Figma MCP.
   Refresh it during a sync: run the --figma-script output in use_figma and save the returned JSON over the
   snapshot. Which controls are measured, and how, is in tokens/component-map.json. An intended difference
   goes in that entry's "allow" as "property": "reason". CSS is measured in the dark theme at default density. */
import { createServer } from "node:http";
import { readFileSync, existsSync, statSync } from "node:fs";
import { spawn, execFileSync } from "node:child_process";
import { dirname, join, extname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const map = JSON.parse(readFileSync(join(ROOT, "tokens/component-map.json"), "utf8")).entries;

if (args.includes("--figma-script")) {
  const MAP = map.map((e) => ({ key: e.key, ...e.figma }));
  console.log(`/* Read-only. Run in the Figma MCP use_figma tool on file VZxmDNQiosTN6gqnvEQ65Z, then save the returned JSON
   over tokens/figma-components.json. Generated by: node tools/component-drift.mjs --figma-script */
const MAP = ${JSON.stringify(MAP)};
const cols = await figma.variables.getLocalVariableCollectionsAsync();
const byId = {}, colOf = {};
for (const c of cols) for (const id of c.variableIds) { byId[id] = await figma.variables.getVariableByIdAsync(id); colOf[id] = c; }
const hex = (c, a) => "#" + [c.r, c.g, c.b].map((v) => Math.round(v * 255).toString(16).padStart(2, "0")).join("") + (a < 1 ? Math.round(a * 255).toString(16).padStart(2, "0") : "");
const resolve = (v, d = 0) => { const val = v.valuesByMode[colOf[v.id].modes[0].modeId]; return val && val.type === "VARIABLE_ALIAS" && d < 8 ? resolve(byId[val.id], d + 1) : val; };
const pairs = (s) => s.split(",").map((x) => x.trim()).sort().join(",");
const paint = (list) => {
  const f = (list || []).filter((p) => p.visible !== false)[0];
  if (!f) return { value: "none", variable: "", tier: "" };
  if (f.type !== "SOLID") return { value: f.type, variable: "", tier: "" };
  const o = f.opacity === undefined ? 1 : f.opacity, b = f.boundVariables && f.boundVariables.color;
  if (!b) return { value: hex(f.color, o), variable: "", tier: "raw" };
  const r = resolve(byId[b.id]);
  return { value: hex(r, (r.a === undefined ? 1 : r.a) * o), variable: byId[b.id].name, tier: colOf[b.id].name.split(" / ")[0] };
};
const out = {};
for (const m of MAP) {
  const node = await figma.getNodeByIdAsync(m.node);
  if (!node) { out[m.key] = { error: "node " + m.node + " not found" }; continue; }
  let v = node;
  if (node.type === "COMPONENT_SET") { v = node.children.find((k) => pairs(k.name) === pairs(m.variant)); if (!v) { out[m.key] = { error: "variant not found: " + m.variant + ". Set has: " + [...new Set(node.children.map((k) => k.name))].slice(0, 8).join(" | ") }; continue; } }
  const t = m.part ? v.findOne((n) => n.name === m.part) : v;
  if (!t) { out[m.key] = { error: "layer not found: " + m.part }; continue; }
  const rv = (t.boundVariables || {}).topLeftRadius;
  const fill = paint(t.fills), stroke = paint(t.strokes);
  out[m.key] = { radius: typeof t.cornerRadius === "number" ? t.cornerRadius : "mixed", radiusVar: rv ? byId[rv.id].name : "", height: Math.round(t.height * 10) / 10, fill: fill.value, fillVar: fill.variable, fillTier: fill.tier, stroke: stroke.value };
}
return JSON.stringify({ file: figma.fileKey || "VZxmDNQiosTN6gqnvEQ65Z", captured: new Date().toISOString().slice(0, 10), components: out });`);
  process.exit(0);
}

/* ---------- CSS side: render each control and read its computed style ---------- */
const findChrome = () => {
  const c = [process.env.CHROME, "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", "/Applications/Chromium.app/Contents/MacOS/Chromium"].filter(Boolean);
  for (const p of c) if (existsSync(p)) return p;
  for (const n of ["google-chrome", "chromium", "chromium-browser"]) { try { return execFileSync("which", [n], { encoding: "utf8" }).trim(); } catch {} }
  return null;
};
const chrome = findChrome();
if (!chrome) { console.error("component drift skipped: no Chrome found (set CHROME=/path/to/chrome)."); process.exit(2); }
const esc = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const page = `<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="/css/tokens.css"><link rel="stylesheet" href="/css/components.css"></head><body>
${map.map((e) => `<div data-cd="${esc(e.key)}" data-sel="${esc(e.selector)}" style="display:block;margin:8px;width:320px">${e.html}</div>`).join("\n")}
<script>
const toHex = (c) => { const m = c.match(/^rgba?\\(([\\d.]+),\\s*([\\d.]+),\\s*([\\d.]+)(?:,\\s*([\\d.]+))?\\)$/); if (!m) return c; const a = m[4] === undefined ? 1 : +m[4]; if (a === 0) return "none"; return "#" + [m[1], m[2], m[3]].map((v) => Math.round(+v).toString(16).padStart(2, "0")).join("") + (a < 1 ? Math.round(a * 255).toString(16).padStart(2, "0") : ""); };
const res = {};
document.querySelectorAll("[data-cd]").forEach((w) => {
  const el = w.querySelector(w.dataset.sel);
  if (!el) { res[w.dataset.cd] = { error: "selector matched nothing: " + w.dataset.sel }; return; }
  const cs = getComputedStyle(el);
  res[w.dataset.cd] = { radius: parseFloat(cs.borderTopLeftRadius), height: Math.round(el.getBoundingClientRect().height * 10) / 10, fill: toHex(cs.backgroundColor), stroke: parseFloat(cs.borderTopWidth) > 0 ? toHex(cs.borderTopColor) : "none" };
});
const s = document.createElement("script"); s.type = "application/json"; s.id = "cd-result"; s.textContent = JSON.stringify(res); document.body.appendChild(s);
</script></body></html>`;
const TYPES = { ".css": "text/css", ".woff2": "font/woff2" };
const server = createServer((req, res) => {
  const url = decodeURIComponent((req.url || "/").split("?")[0]);
  if (url === "/") { res.setHeader("content-type", "text/html"); return res.end(page); }
  const p = join(ROOT, url);
  if (!p.startsWith(ROOT) || !existsSync(p) || !statSync(p).isFile()) { res.statusCode = 404; return res.end("not found"); }
  res.setHeader("content-type", TYPES[extname(p)] || "application/octet-stream"); res.end(readFileSync(p));
});
await new Promise((r) => server.listen(0, "127.0.0.1", r));
const dom = await new Promise((resolve) => {
  const p = spawn(chrome, ["--headless=new", "--disable-gpu", "--no-sandbox", "--window-size=1200,900", "--virtual-time-budget=10000", "--dump-dom", `http://127.0.0.1:${server.address().port}/`], { stdio: ["ignore", "pipe", "ignore"] });
  let out = ""; p.stdout.on("data", (d) => (out += d));
  const t = setTimeout(() => p.kill(), 60000);
  p.on("close", () => { clearTimeout(t); resolve(out); });
});
server.close();
const got = dom.match(/<script type="application\/json" id="cd-result">([\s\S]*?)<\/script>/);
if (!got) { console.error("component drift skipped: the page returned no result."); process.exit(2); }
const css = JSON.parse(got[1].replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">"));
if (args.includes("--css")) { console.log(JSON.stringify(css, null, 1)); process.exit(0); }

/* ---------- compare ---------- */
const snapPath = join(ROOT, "tokens/figma-components.json");
if (!existsSync(snapPath)) { console.error("component drift skipped: tokens/figma-components.json is missing. Run --figma-script in the Figma MCP and save its result there."); process.exit(2); }
const snap = JSON.parse(readFileSync(snapPath, "utf8"));
const norm = (v) => { v = String(v).toLowerCase(); return /^#[0-9a-f]{8}$/.test(v) && v.endsWith("ff") ? v.slice(0, 7) : v; };
const diffs = [], allowed = [];
let compared = 0;
for (const e of map) {
  const f = snap.components[e.key], c = css[e.key], allow = e.allow || {};
  const add = (prop, msg) => (allow[prop] ? allowed : diffs).push(`${e.key} [${prop}]  ${msg}`);
  if (!f) { add("snapshot", "not in the Figma snapshot; refresh it"); continue; }
  if (f.error) { add("figma", f.error); continue; }
  if (!c || c.error) { add("css", c ? c.error : "not rendered"); continue; }
  compared++;
  if (f.radius !== c.radius) add("radius", `Figma ${f.radius}px | CSS ${c.radius}px`);
  if (Math.abs(f.height - c.height) > 0.5) add("height", `Figma ${f.height}px | CSS ${c.height}px`);
  if (norm(f.fill) !== norm(c.fill)) add("fill", `Figma ${f.fill}${f.fillVar ? " (" + f.fillVar + ")" : ""} | CSS ${c.fill}`);
  if (norm(f.stroke) !== norm(c.stroke)) add("border", `Figma ${f.stroke} | CSS ${c.stroke}`);
  if (f.fill !== "none" && f.fillTier !== "Semantic") add("binding", `Figma fill is ${f.fillTier === "raw" ? "a raw color" : "the primitive " + f.fillVar}, not a semantic variable`);
  if (f.radius > 0 && !f.radiusVar) add("binding-radius", "Figma radius is typed, not bound to a radius variable");
}
console.log(`NorthStar component drift: ${compared} controls compared against the Figma snapshot of ${snap.captured || "unknown date"}\n`);
if (allowed.length) console.log(`${allowed.length} intended difference(s) listed in tokens/component-map.json.\n`);
if (!diffs.length) { console.log("Components match Figma."); process.exit(0); }
console.log(`${diffs.length} difference(s):`);
diffs.forEach((d) => console.log("  " + d));
console.log('\nFix the side that is wrong, refresh the snapshot, or record an intended difference in the map entry as "allow": { "property": "reason" }.');
process.exit(1);
